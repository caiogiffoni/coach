"""Alembic migrations match the ORM models and adopt legacy databases."""

from pathlib import Path

from alembic.script import ScriptDirectory
from sqlalchemy import create_engine, inspect, text

from alembic import command
from app.db import (
    BASELINE_REVISION,
    Base,
    alembic_config,
    import_all_models,
    is_unversioned_database,
    upgrade_database,
)


def sqlite_url(tmp_path: Path) -> str:
    return f"sqlite:///{tmp_path / 'coach.db'}"


def table_columns(url: str) -> dict[str, set[str]]:
    engine = create_engine(url)
    try:
        inspector = inspect(engine)
        return {
            name: {col["name"] for col in inspector.get_columns(name)}
            for name in inspector.get_table_names()
            if name != "alembic_version"
        }
    finally:
        engine.dispose()


def current_revision(url: str) -> str:
    engine = create_engine(url)
    with engine.connect() as conn:
        revision = conn.execute(
            text("SELECT version_num FROM alembic_version")
        ).scalar_one()
    engine.dispose()
    return revision


def test_upgrade_on_fresh_db_matches_models(tmp_path):
    import_all_models()
    url = sqlite_url(tmp_path)
    upgrade_database(url)
    expected = {
        name: {col.name for col in table.columns}
        for name, table in Base.metadata.tables.items()
    }
    assert table_columns(url) == expected


def test_models_have_no_unmigrated_changes(tmp_path):
    url = sqlite_url(tmp_path)
    upgrade_database(url)
    # Raises AutogenerateDiffsDetected if a model changed without a migration.
    command.check(alembic_config(url))


def test_fresh_db_is_not_unversioned(tmp_path):
    assert not is_unversioned_database(sqlite_url(tmp_path))


def test_legacy_create_all_db_is_stamped_then_upgraded(tmp_path):
    import_all_models()
    url = sqlite_url(tmp_path)
    engine = create_engine(url)
    Base.metadata.create_all(engine)
    engine.dispose()
    assert is_unversioned_database(url)
    upgrade_database(url)
    assert not is_unversioned_database(url)
    head = ScriptDirectory.from_config(alembic_config(url)).get_current_head()
    assert current_revision(url) == head


def test_baseline_revision_is_the_root_revision(tmp_path):
    script = ScriptDirectory.from_config(alembic_config(sqlite_url(tmp_path)))
    assert script.get_base() == BASELINE_REVISION
